import assert from 'node:assert/strict';
import {actionPointTypes,actionPointMatches,pointApproach} from '../dist/point-access.mjs';
const actor={x:0,y:1.72,z:0},point={type:'hardware',x:5,z:0},open=()=>false;
assert(pointApproach(actor,point,open));assert(!pointApproach(actor,{...point,x:5.001},open));
assert(!pointApproach(actor,point,x=>x>2.1&&x<2.25));
assert(!pointApproach(actor,point,x=>x===0));assert(!pointApproach(actor,point,x=>x===5));
assert(!pointApproach({...actor,y:3},point,open));assert(pointApproach({...actor,y:1.12},point,open));
for(const bad of [NaN,Infinity,-Infinity])assert(!pointApproach({...actor,x:bad},point,open));
let probes=0;assert(!pointApproach(actor,{...point,x:1e9},()=>{probes++;return false}));assert.equal(probes,0);
const before=JSON.stringify([actor,point]);pointApproach(actor,point,open);assert.equal(JSON.stringify([actor,point]),before);
assert.equal(actionPointTypes('list'),null);assert.equal(actionPointTypes('cancelDeal'),null);
assert.equal(actionPointTypes('__proto__'),null);assert.equal(actionPointTypes('toString'),null);
assert.deepEqual(actionPointTypes('batch',{kind:'mix'}),['mix']);assert.deepEqual(actionPointTypes('batch',{kind:'pack'}),['craft']);assert.deepEqual(actionPointTypes('batch',{kind:'bad'}),[]);
assert(actionPointMatches(point,'buyCan'));assert(!actionPointMatches(point,'hire'));
assert(actionPointMatches({type:'staffboard'},'worker'));assert(!actionPointMatches({type:'staffboard'},'hire'));
assert(actionPointMatches({type:'tent',i:2},'water',2));assert(!actionPointMatches({type:'tent',i:2},'water','2'));assert(!actionPointMatches({type:'tent',i:2},'water',1));
assert(actionPointMatches({type:'workshop'},'house'));assert(actionPointMatches({type:'property'},'rent'));
assert(Object.isFrozen(actionPointTypes('buyCan')));
console.log('PASS: action-to-point rules, counter-side approach, wall/elevation/finite/range boundaries, tent indices, immutable inputs and bounded collision probes.');
