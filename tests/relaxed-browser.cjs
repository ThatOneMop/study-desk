const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/#games');
 const total=await page.evaluate(()=>GAME_CATALOG.length);
 assert.equal(await page.locator('.game').count(),total);
 assert.equal(await page.locator('#studyBtn,#playerStudy').count(),0);
 await page.locator('#search').fill('poker balatro');
 assert.equal(await page.locator('.game').count(),1);
 await page.locator('#clearFilters').click();
 await page.locator('#genre').selectOption('Fishing');
 assert.equal(await page.locator('.game').count(),2);
 await page.locator('#search').fill('no matching game');
 assert.equal(await page.locator('.empty').count(),1);
 await page.locator('.empty button').click();
 await page.locator('#groupBy').selectOption('collection');
 assert.equal(await page.locator('.game-section').count(),2);
 await page.locator('#groupBy').selectOption('none');
 await page.locator('#sortGames').selectOption('az');
 const titles=await page.locator('.game h3').allTextContents();
 assert.deepEqual(titles,[...titles].sort((a,b)=>a.localeCompare(b)));
 await page.locator('.fav').first().click();
 await page.getByRole('button',{name:'Favourites',exact:true}).click();
 assert.equal(await page.locator('.game').count(),1);
 await page.locator('#clearFilters').click();
 await page.screenshot({path:'/tmp/study-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'/tmp/study-mobile.png',fullPage:true});
 await page.locator('[data-action="play"][data-game="autumn-drift"]').click();
 await page.waitForFunction(()=>document.querySelector('#frame').contentWindow.StudyBridge);
 await page.locator('#libraryBtn').click();
 assert.equal(await page.locator('#sessionReturn').isVisible(),true);
 assert.deepEqual(errors,[]);
 console.log('PASS: search, genre, empty/reset, grouping, sorting, favourites, mobile overflow, game launch and return; no browser errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
