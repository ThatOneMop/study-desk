import assert from 'node:assert/strict';
import * as THREE from '../dist/vendor/three.module.min.js';
import {PERSON_MESH_PARTS,PEOPLE_FACE_COLS,faceCell} from '../dist/people-kit.mjs';
import {STREET_CROWD_COLLIDERS,STREET_CROWD_FAR,STREET_CROWD_SIZE,STREET_CROWD_PARTS,STREET_CROWD_PART_INDEX,crowdPlan,crowdPalette,createStreetCrowd} from '../dist/street-crowd.mjs';

assert.equal(STREET_CROWD_COLLIDERS.length,0);
assert.equal(STREET_CROWD_FAR,40);
assert.ok(STREET_CROWD_SIZE>=24);
assert.ok(STREET_CROWD_PARTS.some(part=>part.name==='face'&&part.far===false));
assert.ok(STREET_CROWD_PARTS.some(part=>part.name==='torso'&&part.far===true));

const morning=Array.from({length:STREET_CROWD_SIZE},(_,id)=>crowdPlan(id,540));
const night=Array.from({length:STREET_CROWD_SIZE},(_,id)=>crowdPlan(id,1320));
const activities=new Set(morning.map(plan=>plan.activity));
assert.ok(activities.has('work')&&activities.has('street')&&activities.has('sit'));
assert.ok(morning.filter(plan=>Math.abs(plan.z)<18).length>=16,'daytime plans stay on the walked streets');
assert.equal(night.filter(plan=>plan.activity==='home'&&plan.pose==='sit').length,STREET_CROWD_SIZE);
assert.notEqual(crowdPlan(1,540).x,crowdPlan(1,1320).x);
assert.equal(crowdPlan(1,760).activity,'vend');
assert.equal(crowdPlan(2,800).activity,'atm');
const colors=new Set(Array.from({length:12},(_,id)=>crowdPalette(id).skin));
assert.ok(colors.size>=6);
assert.equal(crowdPalette(1).hoodie,true);
assert.equal(crowdPalette(0).outfit,0x4a6d96);

const scene=new THREE.Scene();
assert.throws(()=>createStreetCrowd({scene:null}),TypeError);
assert.throws(()=>createStreetCrowd({scene,capacity:3}),RangeError);
const blocked=(x,z)=>Math.abs(x)<.2&&Math.abs(z)<.2;
const crowd=createStreetCrowd({THREE,scene,blocked,floorHeight:()=>0,capacity:32,time:540});
assert.equal(crowd.drawCalls,4);
assert.equal(crowd.mesh.material.vertexColors,false,'instance colour alone; vertexColors without a colour attribute renders black');
assert.ok(crowd.mesh.instanceColor&&crowd.headMesh.instanceColor);
assert.equal(crowd.counts.colliders,0);
assert.equal(crowd.counts.people,32);
assert.ok(crowd.counts.trianglesNear<=4000,'v154 smoother bodies stay under 4k triangles a person (draw calls unchanged)');assert.equal(crowd.bodyMesh.material.vertexColors,false);
assert.ok(crowd.counts.trianglesFar<crowd.counts.trianglesNear);
assert.equal(crowd.mesh.geometry,crowd.propMesh.geometry);
crowd.sync(540);
const matrix=new THREE.Matrix4(),position=new THREE.Vector3(),quaternion=new THREE.Quaternion(),scale=new THREE.Vector3();
const eye=STREET_CROWD_PART_INDEX.face,torso=STREET_CROWD_PART_INDEX.torso,boxStride=PERSON_MESH_PARTS.round.length;
const camera=new THREE.PerspectiveCamera();
const person=crowd.people[0];
camera.position.set(person.x+3,1.6,person.z);
crowd.update({dt:0,now:0,time:540,camera,active:true});
crowd.faceMesh.getMatrixAt(eye,matrix);matrix.decompose(position,quaternion,scale);
assert.ok(scale.y>.2,'close faces stay on the head');
assert.ok(position.y>1.4&&position.y<1.85,'the painted face sits at head height on a 1.6-1.9 m person');
camera.position.set(person.x,1.6,person.z+55);
crowd.update({dt:0,now:0,time:540,camera,active:true});
crowd.faceMesh.getMatrixAt(eye,matrix);matrix.decompose(position,quaternion,scale);
assert.equal(scale.x,0,'past 40 m the face detail drops out');
crowd.bodyMesh.getMatrixAt(torso,matrix);matrix.decompose(position,quaternion,scale);
assert.ok(scale.y>.2,'the far silhouette keeps a torso');
const standY=(()=>{camera.position.set(person.x,1.6,person.z+3);crowd.sync(540);crowd.update({dt:0,now:1,time:540,camera,active:true});crowd.bodyMesh.getMatrixAt(torso,matrix);matrix.decompose(position,quaternion,scale);return position.y;})();
camera.position.set(crowd.people.find(entry=>crowdPlan(entry.id,540).pose==='sit').x,1.6,3);
crowd.sync(540);crowd.update({dt:0,now:1,time:540,camera,active:true});
const sitter=crowd.people.find(entry=>entry.pose==='sit');
crowd.bodyMesh.getMatrixAt(sitter.id*boxStride+torso,matrix);matrix.decompose(position,quaternion,scale);
assert.ok(position.y<standY-.2,'sitting drops the body onto the bench');
assert.equal(crowd.update({dt:.05,now:2,time:540,camera,active:false}).near>=0,true);
assert.equal(crowd.mesh.visible,false);
const shared=new Set(Array.from({length:STREET_CROWD_SIZE},(_,id)=>crowdPlan(id,540)).map(plan=>plan.x.toFixed(2)+','+plan.z.toFixed(2)));
assert.ok(shared.size>=STREET_CROWD_SIZE-4,'people sharing a job or bench stand side by side, not inside each other');
const faces=crowd.faceMesh.geometry.getAttribute('aFace');assert.ok(faces.array.every(v=>v>=0&&v<PEOPLE_FACE_COLS*3));
console.log('PASS: 32 scheduled townsfolk share one instanced batch, fill the daytime streets, sit at benches, use ATMs and vending machines, go home at night, and drop face detail past 40 m.');
