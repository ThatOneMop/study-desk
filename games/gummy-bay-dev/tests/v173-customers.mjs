import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from '../dist/vendor/three.module.min.js';
import {STARTER_PROFILES,NEW_CUSTOMERS,TOWN_CUSTOMERS,CUSTOMER_LOOKS,lookSignature,introductions,canApproach,sampleVerdict,canSample} from '../dist/customer-roster.mjs';
import {createCustomerCrowd} from '../dist/customer-crowd.mjs';
import {areaOpen,bestBatchQuality,gateText,gearRows} from '../dist/progression-book.mjs';
import {effectById} from '../dist/mix-core.mjs';
import {levelOf,migrateXp} from '../dist/xp-curve.mjs';

const ORIGINAL=['Jules','Benji','Nina','Oz','Frankie',...NEW_CUSTOMERS.map(c=>c.name)];
assert.equal(STARTER_PROFILES.length+NEW_CUSTOMERS.length,14);
assert.equal(TOWN_CUSTOMERS.length,36);
assert.equal(ORIGINAL.length+TOWN_CUSTOMERS.length,50);
assert.equal(CUSTOMER_LOOKS.length,50);
const names=[...ORIGINAL,...TOWN_CUSTOMERS.map(c=>c.name)];
assert.equal(new Set(names).size,50,'every customer has a distinct name');
const sigs=CUSTOMER_LOOKS.map(lookSignature);
assert.equal(new Set(sigs).size,50,'no two locals share a look');
for(const c of TOWN_CUSTOMERS){
 assert.ok(c.effects.length>=2&&c.effects.every(effectById),c.name+' effects');
 assert.ok(c.spend[0]<c.spend[1],c.name+' spend');
 assert.ok(c.personality&&c.area&&c.gate&&c.visual,c.name+' book fields');
 assert.ok(!/drug|weed|cocaine|kill|gun/i.test(c.line+c.personality+c.role),c.name+' stays family friendly');
}
assert.deepEqual(ORIGINAL.slice(0,5),['Jules','Benji','Nina','Oz','Frankie']);
const marlowe=NEW_CUSTOMERS[0];
assert.deepEqual(introductions(marlowe).slice(),[0,6],'original knows stay one hop');
const milo=TOWN_CUSTOMERS.find(c=>c.name==='Milo');
assert.ok(introductions(milo).every(i=>i>=14)&&introductions(milo).length===2,'Milo introduces two town contacts');
assert.equal(canApproach(marlowe,{level:20,quality:1,areaOpen:()=>true}),false,'original locals stay on the vouch chain');
assert.equal(canSample({},[...ORIGINAL.map(name=>({name,knows:[]})),...TOWN_CUSTOMERS],14),false);
assert.equal(canApproach(milo,{level:1,quality:0}),false);
assert.equal(canApproach(milo,{level:2,quality:0}),true);
const west=TOWN_CUSTOMERS.find(c=>c.name==='Ada Pebble');
assert.equal(canApproach(west,{level:9,quality:1,areaOpen:()=>false}),false);
assert.equal(canApproach(west,{level:1,quality:0,areaOpen:id=>id==='westside'}),true);
assert.equal(canApproach(milo,{level:1,unlocked:true}),true);
const fan=sampleVerdict(milo,{enjoyment:.8}),mid=sampleVerdict(milo,{enjoyment:.55}),nope=sampleVerdict(milo,{enjoyment:.2});
assert.equal(fan.accept,true);assert.equal(mid.accept,true);assert.equal(nope.accept,false);
assert.ok(fan.tone!==nope.tone);
assert.equal(areaOpen('old-town',{level:1,quality:0}),true);
assert.equal(areaOpen('westside',{level:2,quality:1}),false);
assert.equal(areaOpen('westside',{level:3,quality:0}),true);
assert.equal(areaOpen('east-market',{level:1,quality:.5}),true,'quality can open an or-district');
assert.equal(areaOpen('east-market',{level:5,quality:0}),true);
assert.equal(areaOpen('west-harbor',{level:6,quality:.4}),false);
assert.equal(areaOpen('west-harbor',{level:6,quality:.55}),true);
assert.match(gateText(milo.gate,{level:1,quality:0}),/level 2/);
assert.equal(bestBatchQuality({packQuality:[.2],gummyQuality:[.4,.7],rawQuality:[.1]}),.7);
assert.equal(bestBatchQuality({}),0);
assert.ok(gearRows(1).some(row=>!row.open&&/level 2/.test(row.need)));
assert.ok(gearRows(7).every(row=>row.open));
assert.equal(levelOf(migrateXp(30).xp),2);
assert.equal(levelOf(migrateXp(510).xp),8);
const scene=new THREE.Scene();
const crowd=createCustomerCrowd({THREE,scene,contacts:TOWN_CUSTOMERS,people:TOWN_CUSTOMERS.map(()=>new THREE.Group()),looks:CUSTOMER_LOOKS.slice(14)});
assert.equal(crowd.drawCalls,3);
assert.equal(crowd.update({now:0,pose:()=>({show:true,x:0,z:0,yaw:0,moving:false})}),36);
