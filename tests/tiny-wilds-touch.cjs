const {JSDOM}=require('jsdom'),fs=require('fs'),path=require('path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(root+'/games/tiny-wilds/index.html','utf8');
const dom=new JSDOM(html,{url:'https://example.test/games/tiny-wilds/',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,d=w.document;
w.HTMLCanvasElement.prototype.getContext=()=>({imageSmoothingEnabled:true});
w.requestAnimationFrame=()=>1;
w.eval(fs.readFileSync(root+'/games/tiny-wilds/save.js','utf8'));
w.eval(fs.readFileSync(root+'/games/tiny-wilds/game.js','utf8')+';window.__probe=()=>({touch:{...touch},holding,x:player.x,y:player.y,keys:{...keys},state});window.step=step;window.action=action;');
const right=d.querySelector('[data-direction="ArrowRight"]');
const pointer=(type,id)=>{const event=new w.Event(type,{bubbles:true,cancelable:true});event.pointerId=id;event.clientX=20;event.clientY=20;return event};
right.dispatchEvent(pointer('pointerdown',1));
assert.equal(w.__probe().touch.ArrowRight,true);
const before=w.__probe().x;
w.step(.5);
assert(w.__probe().x>before,'held touch arrow walks the angler');
w.dispatchEvent(new w.KeyboardEvent('keydown',{code:'ArrowUp',key:'ArrowUp',bubbles:true}));
w.dispatchEvent(pointer('pointerup',1));
assert.equal(w.__probe().touch.ArrowRight,false,'releasing the touch arrow stops that direction');
assert.equal(w.__probe().keys.ArrowUp,true,'a touch release leaves keyboard movement alone');
w.action();
w.step(4);
assert.equal(w.__probe().state,'bite');
w.action();
assert.equal(w.__probe().state,'reeling');
d.getElementById('action').dispatchEvent(pointer('pointerdown',2));
right.dispatchEvent(pointer('pointerdown',3));
assert.equal(w.__probe().holding,true);
assert.equal(w.__probe().touch.ArrowRight,true);
w.dispatchEvent(pointer('pointerup',3));
assert.equal(w.__probe().holding,true,'releasing a direction keeps the reel held');
assert.equal(w.__probe().keys.ArrowUp,true);
w.dispatchEvent(pointer('pointerup',2));
assert.equal(w.__probe().holding,false);
dom.window.close();
console.log('PASS Tiny Wilds touch: direction hold walks, and a second finger can reel without cancelling the other input.');
