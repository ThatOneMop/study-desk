const assert=require('node:assert/strict'),fs=require('fs'),{JSDOM}=require('jsdom');
const root=__dirname+'/../';
function boot(entries={}){
 const dom=new JSDOM(fs.readFileSync(root+'index.html','utf8'),{url:'https://example.test/#games',runScripts:'outside-only',pretendToBeVisual:true});
 const w=dom.window,d=w.document,$=id=>d.getElementById(id);
 w.matchMedia=()=>({matches:false});
 w.confirm=()=>true;
 for(const [key,value] of Object.entries(entries))w.localStorage.setItem(key,value);
 w.eval(fs.readFileSync(root+'catalog.js','utf8'));
 w.eval(fs.readFileSync(root+'app.js','utf8'));
 return {w,d,$,close:()=>w.close()};
}
const hub={favourites:['autumn-drift','retired-fav'],recent:['after-hours','retired-recent'],plays:{tidepost:3}};
const g=boot({'after-class-hub-v1':JSON.stringify(hub)});
const {w,d,$}=g;
assert.equal($('heroTrack').querySelector('h3').textContent,'Gummy Bay');
assert.equal($('heroCarousel').getAttribute('aria-roledescription'),'carousel');
assert.equal(d.querySelectorAll('#heroCarousel [data-action="play"], .shelf [data-action="play"], #heroCarousel .game, .shelf .game, .shelf .fav').length,0);
assert.equal($('heroPause').getAttribute('aria-pressed'),'false');
$('heroPause').click();
assert.equal($('heroPause').getAttribute('aria-pressed'),'true');
assert.equal($('heroPause').textContent,'Play');
assert.equal($('continuePlaying').hidden,false);
assert.match($('continueRow').textContent,/After Hours/);
assert.match($('continueRow').querySelector('button').getAttribute('aria-label'),/Continue playing After Hours/);
assert.equal($('trendingRow').hidden,false);
assert.match($('trendingCards').textContent,/Tidepost/);
assert.equal($('newRow').hidden,false);
assert.match($('newCards').querySelector('.capsule-title').textContent,/Lumen Grove/);
assert.equal($('favouriteShelf').hidden,false);
assert.match($('favouriteRow').textContent,/Autumn Drift/);
assert.equal($('favouriteRow').querySelector('.game'),null);
assert.equal(d.querySelectorAll('.game').length,w.GAME_CATALOG.length);
const launch=d.querySelector('[data-action="play"][data-game="autumn-drift"]');
launch.click();
assert.equal(JSON.parse(w.localStorage.getItem('after-class-hub-v1')).plays['autumn-drift'],1);
launch.click();
const saved=JSON.parse(w.localStorage.getItem('after-class-hub-v1'));
assert.equal(saved.plays['autumn-drift'],1,'returning to the open game does not count another session');
assert.equal(saved.plays.tidepost,3);
assert.ok(saved.favourites.includes('retired-fav'));
assert.ok(saved.recent.includes('retired-recent'));
$('libraryBtn').click();
d.querySelector('#tagFilters button[data-tag="Offline"]').click();
assert.equal(d.querySelectorAll('.game').length,w.GAME_CATALOG.filter(game=>!game.internet).length);
assert.equal(d.querySelector('[data-game="forge-arena"]'),null);
d.querySelector('#tagFilters button[data-tag="All"]').click();
assert.equal(d.querySelectorAll('.game').length,w.GAME_CATALOG.length);
d.querySelector('#genreChips button[data-genre="Fishing"]').click();
assert.equal(d.querySelectorAll('.game').length,2);
assert.equal($('heroCarousel').hidden,true);
$('clearFilters').click();
assert.equal($('genre').value,'all');
assert.equal(d.querySelectorAll('.game').length,w.GAME_CATALOG.length);
assert.equal($('heroCarousel').hidden,false);
assert.equal(d.documentElement.dataset.theme,'light');
$('themeArcade').click();
assert.equal(d.documentElement.dataset.theme,'dark');
assert.equal(w.localStorage.getItem('study-desk-theme'),'dark');
assert.equal($('themeStudy').textContent,'Light theme');
$('themeStudy').click();
assert.equal(w.localStorage.getItem('study-desk-theme'),'light');
assert.equal($('soundToggle').getAttribute('aria-pressed'),'false');
assert.equal($('soundToggle').textContent,'Sound on');
$('soundToggle').click();
assert.equal($('soundToggle').getAttribute('aria-pressed'),'true');
assert.equal(w.localStorage.getItem('study-desk-sound'),'off');
assert.equal($('importSaves').hasAttribute('hidden'),false);
assert.equal($('importSavesArcade').hasAttribute('hidden'),false);
assert.equal($('importSaves').getAttribute('accept'),'.json,application/json,text/plain');
const before=w.location.hash;
$('randomGame').click();
assert.equal($('player').hidden,false);
assert.ok(w.GAME_CATALOG.some(game=>game.type==='bundled'&&game.url===$('frame').getAttribute('src')));
assert.notEqual(before,'ignored');
g.close();
console.log('PASS storefront: Gummy Bay carousel, continue, trending, new, favourites, tags, theme, sound, and random game.');
