import assert from 'node:assert/strict';
import {remoteWorkerStatus,staffAssignment,workerAdvice} from '../dist/staff-status.mjs';
assert.equal(remoteWorkerStatus({status:'Carrying supplies'},true,100),'Carrying supplies');
assert.equal(remoteWorkerStatus({status:'Route blocked'},true,5000),'Route blocked');
assert.equal(remoteWorkerStatus({status:'<script>bad</script>'},true,10),'Awaiting host status');
assert.equal(remoteWorkerStatus({},true,10),'Awaiting host status','older host packet is not interpreted as idle');
assert.equal(remoteWorkerStatus({status:'Pack stored'},false,0),'Host unavailable');
for(const age of [5001,-1,NaN,Infinity])assert.equal(remoteWorkerStatus({status:'Pack stored'},true,age),'Host update stale');
const cfg=Object.freeze({strain:0,tent:1,stock:'stored'}),products=[{name:'Pine Pop'}];
assert.equal(staffAssignment('gardener',cfg,products),'Pine Pop · Tent 2');
assert.equal(staffAssignment('crafter',cfg,products),'Pine Pop · Stockroom packs');
assert.equal(staffAssignment('seller',{strain:-1,stock:'carried'},products),'Any product · Carried packs');
assert.equal(workerAdvice('Missing wrappers').target,'store');
assert.equal(workerAdvice('Missing packaging station').target,'hardware');
assert.equal(workerAdvice('Storage full · holding finished pack').target,'stockroom');
assert.match(workerAdvice('Waiting: property stock full').text,/does not reduce total/);
assert.equal(workerAdvice('Route blocked').target,'craft');
assert.equal(workerAdvice('Host update stale').screen,'network');
assert.match(workerAdvice('Assignment paused').text,/retained/);
assert.match(workerAdvice('Station occupied').text,/Finish or cancel/);
console.log('PASS: authoritative/stale/legacy worker status, safe fixed advice, current assignment summaries and full-stock/cargo guidance.');
