import assert from 'node:assert/strict';
import {policeSight,readPoliceReport,policeFeedback} from '../dist/police-feedback.mjs';
const actor={x:0,z:0},c=(mode,suspicion,x=2)=>({x,z:0,target:'host',mode,suspicion,lost:1});
const state={officers:[c('patrol',100),c('stop',99),c('pursuit',0)],cooldown:0};
const before=JSON.stringify(state);let view=policeFeedback(state,'host',actor,()=>true);
assert.equal(view.stage,'pursuit');assert(view.canComply);assert.equal(JSON.stringify(state),before);
view=policeFeedback({officers:[c('stop',100)]},'host',actor,()=>true);assert(view.message.includes('3s before pursuit'));
assert(!policeFeedback({officers:[c('pursuit',100,18)]},'host',actor,()=>true).canComply);
assert(!policeFeedback(state,'host',actor,()=>false).canComply);
assert.equal(policeFeedback(state,'host',actor,()=>true,{stale:true}).stage,'stale');
assert.equal(policeFeedback(state,'host',actor,()=>true,{connected:false}).stage,'offline');
assert.equal(policeFeedback({...state,search:{role:'guest',remaining:2.1}},'host',actor,()=>true).stage,'search');
assert(policeFeedback({...state,search:{role:'guest',remaining:2.1}},'host',actor,()=>true).message.includes('PARTNER BEING SEARCHED · 3s'));
assert.equal(policeFeedback({officers:[c('patrol',10)]},'host',actor,()=>true).stage,'clear');
assert.equal(policeFeedback({officers:[c('__proto__',100)]},'host',actor,()=>true).stage,'clear');
const report={role:'host',seized:3,fine:84,day:2,fled:true};assert.equal(readPoliceReport(report).seized,3);
assert.equal(policeFeedback({officers:[],report,cooldown:2},'host',actor,()=>true).stage,'report');
assert.equal(readPoliceReport({...report,fine:NaN}),null);assert.equal(readPoliceReport({...report,role:'<script>'}),null);
assert.equal(readPoliceReport({role:'guest',seized:0,fine:0}).day,null,'older report remains readable');
assert(policeSight(actor,{x:2,z:0},()=>false));assert(!policeSight(actor,{x:2,z:0},x=>x>.8&&x<1.1));
assert(!policeSight(actor,{x:2,z:0},x=>x===0));let probes=0;
assert(!policeSight(actor,{x:Infinity,z:0},()=>{probes++;return false}));assert(!policeSight(actor,{x:1e9,z:0},()=>{probes++;return false}));assert.equal(probes,0);
console.log('PASS: police severity, stop countdown, real comply reach/occlusion, partner/stale/disconnected views, safe legacy reports and finite bounded sight.');
