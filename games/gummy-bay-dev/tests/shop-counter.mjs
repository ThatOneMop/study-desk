import assert from 'node:assert/strict';
import {armShopMarkup,shopConfirmHTML,shopRefundHTML,moneyValue,parseActionArgs,shopIcon} from '../dist/shop-counter.mjs';

const row=(title,desc,label,action,disabled=false)=>`<div class="item"><div><strong>${title}</strong><p>${desc}</p></div><button class="primary" onclick="${action}" ${disabled?'disabled':''}>${label}</button></div>`;
const html='<h2>Hank</h2>'+row('Basic grow tent · 0 owned','Reusable tent frame.','$100',"action('buyTent')")+row('Watering can','Fill at the sink.','OWNED',"action('buyCan')",true)+row('Grow lights · 0/3','Level 2.','LEVEL 2',"action('lights')",true)+row('Plant trimmers','Needed to harvest.','$10',"action('buyTrimmers')",true)+row('Pine Pop seed','Harvest 4.','$30',"action('seed',0)");
const armed=armShopMarkup(html);
assert.equal(armed.offers.length,2);
assert.equal(armed.offers[0].action,'buyTent');
assert.deepEqual(armed.offers[0].args,[]);
assert.equal(armed.offers[0].amount,100);
assert.equal(armed.offers[1].action,'seed');
assert.deepEqual(armed.offers[1].args,[0]);
assert.ok(armed.html.includes('openShopConfirm(0)'));
assert.ok(armed.html.includes('class="shop-name">Basic grow tent · 0 owned'));
assert.ok(armed.html.includes('>$100</span>'));
assert.equal(armed.html.includes("action('buyTent')"),false);
assert.ok(armed.html.includes("action('buyCan')"),'owned rows stay on their original action');
assert.ok(armed.html.includes('LEVEL 2'));
assert.ok(armed.html.includes('class="shop-name">Plant trimmers'));
assert.ok(armed.html.includes('disabled'));
assert.equal(armShopMarkup(armed.html).offers.length,0,'arming twice does not nest another confirm');
assert.equal(moneyValue('$1,200'),1200);
assert.equal(moneyValue('LEVEL 2'),null);
assert.deepEqual(parseActionArgs(",0,'van'"),[0,'van']);
assert.equal(shopIcon('buyTent'),'⌂');

const cart=shopConfirmHTML(armed.offers[0],{cash:400,bank:0,payment:'cash'});
assert.ok(cart.includes('CART'));
assert.ok(cart.includes('Basic grow tent'));
assert.ok(cart.includes('Left after this'));
assert.ok(cart.includes('$300'));
assert.ok(cart.includes('Buy now'));
assert.equal(cart.includes('disabled'),false);
const short=shopConfirmHTML({...armed.offers[0],caution:'You already own 1 tent.'},{cash:50,bank:0,payment:'cash'});
assert.ok(short.includes('disabled'));
assert.ok(short.includes('Short'));
assert.ok(short.includes('You already own 1 tent.'));
assert.equal(short.includes('<script'),false);
const hostile=shopConfirmHTML({name:'<Tent>',detail:'a<b>b',price:'$1',amount:1,icon:'⌂'},{cash:10,bank:0});
assert.equal(hostile.includes('<Tent>'),false);
assert.ok(hostile.includes('&lt;Tent&gt;'));
const refund=shopRefundHTML({name:'Basic grow tent',price:'$100'});
assert.ok(refund.includes('id="shopRefund"'));
assert.ok(refund.includes('Refund'));
assert.equal(shopRefundHTML({name:'Can',price:'$15'},true).includes('refundShopPurchase'),false);
console.log('PASS: shop buttons name the item, confirm before charging, and offer a refund.');
