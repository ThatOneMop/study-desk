import assert from 'node:assert/strict';
import {lookPreset,detectLookQuality,lookGrade,createEffects} from '../dist/post-stack.mjs';
assert.equal(lookPreset('performance').composer,false);assert.equal(lookPreset('performance').pixelRatio,1);assert.equal(lookPreset('performance').shadows,false);assert.equal(lookPreset('performance').townDistance,72);assert.equal(lookPreset('low').vignette,'css');
assert.equal(lookPreset('balanced').pixelRatio,1.25);assert.equal(lookPreset('balanced').composer,false);assert.equal(lookPreset('medium').shadows,true);
assert.equal(lookPreset('high').composer,true);assert.equal(lookPreset('high').pixelRatio,1.85);assert.equal(lookPreset('ultra').quality,'high');
assert.equal(lookPreset('nope').quality,'balanced');
assert.equal(detectLookQuality({}),'balanced');
assert.equal(detectLookQuality({software:true}),'performance');
assert.equal(detectLookQuality({coarse:true,cores:8}),'performance');
assert.equal(detectLookQuality({cores:4}),'performance');
assert.equal(detectLookQuality({cores:2,saved:'high'}),'high');
