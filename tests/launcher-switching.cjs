const {JSDOM}=require('jsdom'),fs=require('fs'),assert=require('node:assert/strict');
const root=__dirname+'/../';
const dom=new JSDOM(fs.readFileSync(root+'index.html','utf8'),{url:'https://example.test/repo/',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,d=w.document,$=id=>d.getElementById(id);
let approved=false,prompts=[];w.confirm=message=>{prompts.push(message);return approved};
w.eval(fs.readFileSync(root+'catalog.js','utf8'));w.eval(fs.readFileSync(root+'app.js','utf8'));
const launch=id=>[...d.querySelectorAll('button[data-action="play"]')].find(b=>b.dataset.game===id);
$('openGames').click();launch('after-hours').click();assert.equal(prompts.length,0,'first launch needs no confirmation');
const session=$('frame').contentWindow,src=$('frame').src;
session.document.open();session.document.write('<body><p id="session-marker">unsaved session</p></body>');session.document.close();
const saves={'after-hours-save-v1':'existing game save','study-desk-v1':'existing study data'};
for(const [key,value] of Object.entries(saves))w.localStorage.setItem(key,value);
$('pauseGame').click();$('libraryBtn').click();
const recent=w.localStorage.getItem('after-class-hub-v1');
const other=launch('underleaf');other.focus();other.click();
assert.equal(prompts.length,1,'switching asks before unloading');
assert(prompts[0].includes('After Hours')&&prompts[0].includes('Underleaf')&&prompts[0].includes('Unsaved'));
assert.equal($('frame').contentWindow,session,'cancel keeps same document');
assert.equal($('frame').src,src);assert(session.document.getElementById('session-marker'));
assert.equal($('player').hidden,true);assert.equal(d.activeElement,other,'cancel keeps selected button focus');
assert.equal(w.localStorage.getItem('after-class-hub-v1'),recent,'cancel does not record an unplayed game');
$('sessionReturn').querySelector('button').click();assert.equal(prompts.length,1,'returning needs no confirmation');
assert.equal($('frame').contentWindow,session);assert.equal($('frame').inert,true,'manual pause survives cancellation/return');
$('libraryBtn').click();approved=true;launch('underleaf').click();
assert.equal(prompts.length,2);assert.notEqual($('frame').contentWindow,session);
assert.equal($('frame').title,'Underleaf game');assert.equal($('frame').inert,false);
assert.equal(JSON.parse(w.localStorage.getItem('after-class-hub-v1')).recent[0],'underleaf');
for(const [key,value] of Object.entries(saves))assert.equal(w.localStorage.getItem(key),value,'switch never deletes stored progress');
console.log('PASS switching: initial/same-game prompt-free, named warning, cancelled iframe/session/focus/pause/history preserved, approved switch, stored saves untouched');
w.close();
