import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from '../dist/vendor/three.module.min.js';
import {GLTFLoader} from '../dist/vendor/gltf-loader.js';
import {furnitureFootprint as footprint,furnitureContains as contains,escapeFurniture as escape} from '../dist/furniture-access.mjs';
const rack=footprint('stockrack',0,0,1.2,.8,0),before=JSON.stringify(rack);
assert.ok(Object.isFrozen(rack));assert.equal(rack.w,1.85);assert.equal(rack.d,1.4500000000000002);
for(const values of [[NaN,0,1,1],[0,Infinity,1,1],[0,0,0,1],[0,0,1,-1]])assert.throws(()=>footprint('bad',...values),TypeError);
assert.ok(contains(rack,0,0));assert.equal(contains(rack,rack.w/2,0),false);
for(const [x,z]of [[NaN,0],[0,Infinity]])assert.equal(contains(rack,x,z),false);
assert.equal(contains(null,0,0),false);
const rectangle=(x,z,ignored)=>!ignored?.has(rack)&&contains(rack,x,z);
assert.deepEqual(escape({x:0,z:0},[rack],rectangle),{x:0,z:-.75,distance:.75});
assert.equal(escape({x:2,z:2},[rack],rectangle),null,'do not move a clear saved position');
const wall=(x,z,ignored)=>rectangle(x,z,ignored)||z<-.4;
assert.deepEqual(escape({x:0,z:0},[rack],wall),{x:0,z:.75,distance:.75},'a shorter side cannot tunnel through another wall');
assert.equal(escape({x:0,z:0},[rack],()=>true),null,'sealed world cannot force a teleport');
const blocker={x:.5,z:0,w:1,d:5};
const blockedOther=(x,z,ignored)=>rectangle(x,z,ignored)||contains(blocker,x,z);
assert.equal(escape({x:.1,z:0},[rack],blockedOther),null,'a non-enclosing protected wall is never ignored');
for(const actor of [null,{}, {x:NaN,z:0}])assert.equal(escape(actor,[rack],rectangle),null);
assert.equal(escape({x:0,z:0},null,rectangle),null);
assert.equal(JSON.stringify(rack),before);
const mixer=footprint('mixer',0,0,2.4,1.3,0),mixBlocked=(x,z,ignored)=>!ignored?.has(mixer)&&contains(mixer,x,z);
for(const x of [-1.4,0,1.4])for(const z of [-.8,0,.8]){const actor={x,z},copy=JSON.stringify(actor),safe=escape(actor,[mixer],mixBlocked);assert.ok(safe&&safe.distance<=3&&!mixBlocked(safe.x,safe.z));assert.equal(JSON.stringify(actor),copy);}
const bytes=fs.readFileSync(new URL('../dist/assets/equipment-v11.glb',import.meta.url)),asset=await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),'');
const exportedMixer=asset.scene.getObjectByName('Mixer');assert.ok(exportedMixer);exportedMixer.updateMatrixWorld(true);
const mixerBounds=new THREE.Box3().setFromObject(exportedMixer),size=mixerBounds.getSize(new THREE.Vector3());
assert.ok(Math.abs(size.x-2.4)<1e-6&&Math.abs(size.z-1.3)<1e-6&&Math.abs(mixerBounds.getCenter(new THREE.Vector3()).x)<1e-6);
console.log('CPU unchanged exported Mixer footprint: '+JSON.stringify({min:mixerBounds.min.toArray(),max:mixerBounds.max.toArray(),padded:[mixer.w,mixer.d]}));
console.log('PASS: frozen padded footprints, finite/boundary guards, nearest bounded legacy escape, protected-wall/no-route refusal, no move for clear positions and immutable inputs. Existing 2D collision convention, not rendered furniture or full 3D capsules.');
