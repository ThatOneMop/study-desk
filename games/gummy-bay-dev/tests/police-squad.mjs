import assert from 'node:assert/strict';
import fs from 'node:fs';
import {inVision,VISION_RANGE,VISION_YAW,VISION_PITCH} from '../dist/police-vision.mjs';
import {freshChase,spotChase,stepChase,escalateChase,stageSeconds,LADDER_SECONDS} from '../dist/police-ladder.mjs';
import {hideSpotAt,hidingClears,HIDE_SPOTS} from '../dist/hide-spots.mjs';
import {stepWitness,WITNESS_SECONDS} from '../dist/witness-call.mjs';
import {slipChance,slipZoneOpen,trySlip,SLIP_WINDOW,SLIP_CHANCE_FULL,spareStack} from '../dist/pocket-slip.mjs';
import {bonk,stepKnockout,scuffleWeapon,SCUFFLE_WEAPONS,machineBreaks,KO_HITS,knockLength,COP_HEAT} from '../dist/scuffle.mjs';
import {donutBribe,cashBribe,DONUT_DISTRACT,BRIBE_CHANCE} from '../dist/sugar-bribe.mjs';
import {bustFine,applyBust,wakeClock,FINE_FLOOR,WAKE_AT} from '../dist/busted.mjs';
import {EASE} from '../dist/cinematics.mjs';
import {bustedTimeline,bustedSample,paintMugshot} from '../dist/busted.mjs';
import {firstSaleProtected} from '../dist/sale-shield.mjs';
import {policeBanner} from '../dist/hud-readout.mjs';

const deg=radians=>radians*180/Math.PI;
assert.equal(VISION_RANGE,45);
assert.equal(Math.round(deg(VISION_YAW)),135);
assert.equal(Math.round(deg(VISION_PITCH)),100);
const eye={x:0,y:1.55,z:0,angle:0};
assert.equal(inVision(eye,{x:0,y:1.2,z:10}).seen,true);
assert.equal(inVision(eye,{x:0,y:1.2,z:46}).reason,'range');
assert.equal(inVision(eye,{x:10,y:1.2,z:10}).seen,true,'45° off centre is inside the cone');
assert.equal(inVision(eye,{x:30,y:1.2,z:8}).reason,'yaw');
assert.equal(inVision(eye,{x:0,y:1.55+12,z:6}).reason,'pitch');
assert.equal(inVision(eye,{x:0,y:1.2,z:8},{sight:()=>false}).reason,'blocked');

assert.deepEqual(LADDER_SECONDS,{suspicious:60,investigating:30,pursuit:35,'all-units':45});
let chase=spotChase(freshChase());
assert.equal(chase.stage,'suspicious');
assert.equal(chase.left,60);
chase=stepChase(chase,20,false);
assert.equal(chase.searching,true);
assert.ok(Math.abs(chase.left-40)<1e-9);
chase=stepChase(chase,1,true);
assert.equal(chase.searching,false);
assert.equal(chase.left,60,'seeing the player refills the search timer');
chase=stepChase(chase,0,false);
chase=stepChase(chase,60,false);
assert.equal(chase.stage,'clear','breaking line of sight for the stage timeout clears the chase');
chase=escalateChase(escalateChase(spotChase(freshChase())));
assert.equal(chase.stage,'pursuit');
assert.equal(stageSeconds('pursuit'),35);
chase=stepChase(chase,34,false);
assert.equal(chase.stage,'pursuit');
chase=stepChase(chase,1.1,false);
assert.equal(chase.stage,'clear');
assert.equal(escalateChase({stage:'all-units',left:1}).stage,'all-units');

const dumpster=HIDE_SPOTS.find(spot=>spot.kind==='dumpster');
assert.equal(hideSpotAt(dumpster.x,dumpster.z)?.kind,'dumpster');
assert.equal(hideSpotAt(dumpster.x+8,dumpster.z),null);
const wanted=spotChase(freshChase());
assert.equal(hidingClears(wanted,{inside:true,seen:true}).cleared,false);
assert.equal(hidingClears(wanted,{inside:true,seen:false}).chase.stage,'clear');
assert.equal(hidingClears(wanted,{inside:false,seen:false}).cleared,false);

let call=stepWitness(null,.5,{crime:true});
assert.equal(call.state,'calling');
assert.equal(call.called,false);
call=stepWitness(call,WITNESS_SECONDS,{crime:true});
assert.equal(call.called,true);
assert.equal(stepWitness(null,9,{crime:false}).state,'idle');

assert.equal(slipChance(1),SLIP_CHANCE_FULL);
assert.equal(slipChance(0),0.25);
assert.equal(SLIP_WINDOW,0.35);
assert.equal(slipZoneOpen(0.1,0),true);
assert.equal(slipZoneOpen(0.5,0),false);
assert.equal(trySlip({time:0.1,zone:0,skill:1,roll:0.2}).ok,true);
assert.equal(trySlip({time:0.1,zone:0,skill:1,roll:0.9}).reason,'fumble');
assert.equal(trySlip({time:2,zone:0,skill:1,roll:0}).reason,'window');
assert.deepEqual(spareStack({packs:[2,0],gummies:[0],raw:[0]},0),{key:'packs',index:0,qty:2});

const pan=scuffleWeapon('pan'),baton=scuffleWeapon('baton');
let body=bonk(null,pan,.2);
assert.equal(body.ko,false);
body=bonk(body.target,pan,.2);
body=bonk(body.target,baton,.25);
assert.equal(body.ko,true);
assert.equal(body.target.hits,KO_HITS);
assert.ok(body.down>=4&&body.down<=6);
assert.ok(body.style==='stars'||body.style==='birdies');
let dizzy=body.target;
dizzy=stepKnockout(dizzy,dizzy.ko-0.1);
assert.ok(dizzy.ko>0&&dizzy.ko<1);
dizzy=stepKnockout(dizzy,1);
assert.equal(dizzy.ko,0);
assert.equal(knockLength(0),4);
assert.equal(knockLength(1),6);
assert.equal(machineBreaks(2,pan),true);
assert.equal(machineBreaks(2,baton),false);
assert.equal(bonk(null,'net').kind,'net');
assert.equal(COP_HEAT,40);
const weaponText=SCUFFLE_WEAPONS.map(weapon=>`${weapon.id} ${weapon.name}`).join(' ');
assert.doesNotMatch(weaponText,/gun|pistol|rifle|firearm|shotgun|bullet|blood|knife/i);
const source=fs.readFileSync(new URL('../dist/scuffle.mjs',import.meta.url),'utf8');
assert.doesNotMatch(source,/\b(gun|pistol|rifle|firearm|shotgun|bullet|blood|knife)\b/i);

const bribed=donutBribe(spotChase(freshChase()),2);
assert.equal(bribed.ok,true);
assert.equal(bribed.donuts,1);
assert.equal(bribed.seconds,DONUT_DISTRACT);
assert.equal(bribed.chase.searching,true);
assert.equal(donutBribe(escalateChase(spotChase(freshChase())),2).ok,false);
const paid=cashBribe({stage:'suspicious',left:60},100,BRIBE_CHANCE-0.01);
assert.equal(paid.ok,true);
assert.equal(paid.chase.stage,'clear');
assert.equal(paid.cash,60);
assert.equal(cashBribe({stage:'suspicious'},100,0.9).reason,'refused');
assert.equal(cashBribe({stage:'pursuit'},10,0).reason,'short');

assert.equal(bustFine(100),30);
assert.equal(bustFine(40),FINE_FLOOR);
assert.equal(bustFine(10),10);
assert.equal(bustFine(0),0);
const bust=applyBust({cash:200,bank:500,day:1,time:900,heat:80,raw:[1,0],gummies:[2],packs:[4,1],storedPacks:[9]});
assert.equal(bust.fine,60);
assert.equal(bust.state.cash,140);
assert.equal(bust.state.day,2);
assert.equal(bust.state.time,WAKE_AT);
assert.deepEqual(bust.state.packs,[0,0]);
assert.equal(bust.state.storedPacks,undefined,'stored packs are not part of the bust payload');
assert.equal(bust.seized,1+2+4+1);
assert.deepEqual(wakeClock(3,100),{day:3,time:WAKE_AT});
assert.deepEqual(wakeClock(3,WAKE_AT),{day:4,time:WAKE_AT});

