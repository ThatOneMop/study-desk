import assert from 'node:assert/strict';
import * as THREE from '../dist/vendor/three.module.min.js';
import {chooseParcel,parcelVelocity,PARCEL_NOTES} from '../dist/parcel-handling.mjs';
import {stepProp} from '../dist/prop-motion.mjs';
import {createParcelFinish} from '../dist/parcel-finish.mjs';
const actor={x:0,y:1.72,z:0,yaw:0,pitch:0};
const behind={x:0,y:1.18,z:1},front={x:0,y:1.18,z:-2};
assert.equal(chooseParcel([behind,front],actor,0),1);
assert.equal(chooseParcel([front],actor,Math.PI),-1);
assert.equal(chooseParcel([front],actor,0,0,()=>false),-1);
assert.equal(chooseParcel([{...front,owner:'guest'}],actor,0),-1);
assert.equal(chooseParcel([{x:0,y:.325,z:-1}],actor,0,-.95),0);
assert.equal(chooseParcel([{x:0,y:.325,z:-1}],actor,0,.7),-1);
assert.equal(chooseParcel([front],{...actor,x:NaN},0),-1);
assert(parcelVelocity(0,.8).vy>parcelVelocity(0,0).vy);
assert(parcelVelocity(0,-.8).vy<0);
assert.deepEqual(parcelVelocity(0,0,true),{vx:0,vy:0,vz:0});
assert.deepEqual(parcelVelocity(NaN),{vx:0,vy:0,vz:0});
const clear={blocked:()=>false,floorHeight:()=>0,reachBlocked:()=>false};
const held={...front,owner:'host',vx:0,vy:0,vz:0};
function follow(fps,holder){let p={...held};for(let i=0;i<fps;i++)p=stepProp(p,1/fps,{...clear,holder});return p;}
const at30=follow(30,actor),at120=follow(120,actor);
assert(Math.abs(at30.z-at120.z)<1e-8&&Math.abs(at30.y-at120.y)<1e-8);
assert(follow(60,{...actor,y:1.03}).y<at30.y-.5,'crate lowers when crouching');
assert(follow(60,{...actor,pitch:.7}).y>at30.y+.3,'crate follows vertical view');
const scene=new THREE.Scene(),groups=[new THREE.Group(),new THREE.Group()];groups.forEach(g=>scene.add(g));
const finish=createParcelFinish(scene,groups),resources=finish.fittings.map(m=>m.geometry),children=scene.children.length;
for(let i=0;i<300;i++)finish.update([behind,front],{active:true,floorHeight:()=>0,actor,yaw:0,pitch:0,eligible:()=>true,focused:true});
assert(finish.outline.visible);assert.equal(finish.shadows.count,2);
assert.equal(scene.children.length,children);assert(finish.fittings.every((m,i)=>m.geometry===resources[i]));
finish.update([behind,front],{active:false,floorHeight:()=>0,actor,yaw:0,pitch:0,eligible:()=>true,focused:true});
assert(!finish.outline.visible&&!finish.shadows.visible);
assert.equal(PARCEL_NOTES.length,4);assert.equal(new Set(PARCEL_NOTES.map(n=>n.title)).size,4);
console.log('PASS: aimed/occluded/owned parcel selection, pitched throws, gentle release, crouch carry, 30/120 FPS equivalence, fixed visual resources and notebook notes. CPU only.');
