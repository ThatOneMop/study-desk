const {chromium}=require('playwright');
const assert=require('node:assert/strict'),fs=require('fs');
(async()=>{
 const launch={headless:true,args:['--no-sandbox']};if(process.env.CHROME_PATH)launch.executablePath=process.env.CHROME_PATH;
 const browser=await chromium.launch(launch);
 const page=await browser.newPage({viewport:{width:1280,height:900},acceptDownloads:true}),errors=[],missed=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('response',response=>{const url=new URL(response.url());if(url.hostname==='127.0.0.1'&&response.status()>=400)missed.push(response.status()+' '+url.pathname)});
 await page.goto('http://127.0.0.1:8765/');
 await page.evaluate(()=>{localStorage.setItem('littleLakeV1','{not json');localStorage.setItem('keep-me','stay')});
 await page.reload();
 const pick=await page.locator('#studyMondayPlay').textContent();
 assert.match(pick,/^Play Monday pick: .+/);
 const described=await page.locator('#studyMondayText').textContent();
 assert.match(described,/Week of .+A new bundled game is chosen each Monday/);
 const tree=await page.locator('#studyMonday').ariaSnapshot();
 assert.match(tree,/heading "Monday pick"/);assert.match(tree,/Play Monday pick:/);
 await page.locator('#studyMondayPlay').focus();
 assert.equal(await page.evaluate(()=>document.activeElement.id),'studyMondayPlay');
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#exportSaves').click()]);
 assert.equal(download.suggestedFilename(),'study-desk-saves.json');
 const saved=await download.path();
 const exported=JSON.parse(fs.readFileSync(saved,'utf8'));
 assert.equal(exported.entries.find(entry=>entry.key==='littleLakeV1').value,'{not json');
 assert.match(await page.locator('#saveVaultStatus').textContent(),/Exported/);
 await page.screenshot({path:'/tmp/study-monday-desktop.png',fullPage:true});
 const backup=JSON.stringify({format:'study-desk-saves',version:1,entries:[{key:'littleLakeV1',value:'{"money":4}'},{key:'fresh-game',value:'{"ok":true}'}]});
 fs.writeFileSync('/tmp/study-desk-saves.json',backup);
 const cancelImport=page.locator('#importSaves').setInputFiles('/tmp/study-desk-saves.json');
 await page.waitForFunction(()=>document.getElementById('saveImportDialog').open);
 const listed=await page.locator('#saveImportList').innerText();
 assert.match(listed,/littleLakeV1/);
 assert.match(listed,/fresh-game/);
 assert.match(listed,/replaces the copy on this device/);
 await page.locator('#saveImportCancel').click();
 await cancelImport;
 await page.waitForFunction(()=>/cancelled/i.test(document.querySelector('#saveVaultStatus').textContent));
 assert.equal(await page.evaluate(()=>localStorage.getItem('littleLakeV1')),'{not json');
 const confirmImport=page.locator('#importSaves').setInputFiles('/tmp/study-desk-saves.json');
 await page.waitForFunction(()=>document.getElementById('saveImportDialog').open);
 await Promise.all([page.waitForNavigation({waitUntil:'load'}),page.locator('#saveImportConfirm').click()]);
 await confirmImport.catch(()=>{});
 assert.equal(await page.evaluate(()=>localStorage.getItem('littleLakeV1')),'{"money":4}');
 assert.equal(await page.evaluate(()=>localStorage.getItem('fresh-game')),'{"ok":true}');
 assert.equal(await page.evaluate(()=>localStorage.getItem('keep-me')),'stay');
 await page.keyboard.press('Tab');
 await page.locator('#studyMondayPlay').focus();
 await page.keyboard.press('Enter');
 await page.waitForFunction(()=>document.querySelector('#player').hidden===false);
 assert.match(await page.locator('#playing').textContent(),/.+/);
 await page.locator('#libraryBtn').click();
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://127.0.0.1:8765/#games');
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 const box=await page.locator('#arcadeMondayPlay').boundingBox();
 assert(box.width>=200&&box.x>=0&&box.x+box.width<=390);
 assert.equal(await page.locator('#arcadeMonday').getAttribute('aria-labelledby'),'arcadeMondayTitle');
 await page.locator('#arcadeMonday').scrollIntoViewIfNeeded();
 await page.screenshot({path:'/tmp/study-monday-mobile.png'});
 await page.setViewportSize({width:1280,height:900});
 await page.evaluate(()=>{localStorage.setItem('study-desk-theme','dark');localStorage.setItem('after-class-hub-v1',JSON.stringify({favourites:['gummy-bay','autumn-drift','tidepost'],recent:['little-foundry','after-hours','gummy-bay'],plays:{'gummy-bay':6,tidepost:4,'after-hours':3,'little-foundry':2}}))});
 await page.goto('http://127.0.0.1:8765/#games');
 await page.waitForSelector('#heroTrack h3');
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'/tmp/storefront-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'/tmp/storefront-mobile.png'});
 assert.deepEqual(missed,[]);
 assert.deepEqual(errors,[]);
 console.log('PASS shell browser: Monday pick name, accessibility tree, keyboard focus, completed save download, cancelled and confirmed import, mobile width, storefront, no missing files.');
 console.log(tree);
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
